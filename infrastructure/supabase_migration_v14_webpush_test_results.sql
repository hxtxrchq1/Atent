-- Persist delivery results for authenticated Web Push test requests.
CREATE TABLE IF NOT EXISTS public.web_push_test_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT UNIQUE,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'sent', 'failed')),
  http_status INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_web_push_test_requests_owner
  ON public.web_push_test_requests(user_id, id DESC);

ALTER TABLE public.web_push_test_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.web_push_test_requests FROM PUBLIC, anon, authenticated;

DROP FUNCTION IF EXISTS public.send_web_push_test_session(TEXT, TEXT);

CREATE OR REPLACE FUNCTION public.send_web_push_test_session(p_session_token TEXT, p_endpoint TEXT)
RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_user_id UUID;
  v_bearer TEXT;
  v_request_id BIGINT;
  v_test_id BIGINT;
BEGIN
  SELECT user_id INTO v_user_id FROM public.pwa_sessions
   WHERE token_hash = extensions.digest(convert_to(coalesce(p_session_token, ''), 'UTF8'), 'sha256')
     AND revoked_at IS NULL AND expires_at > now()
   LIMIT 1;
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'Web session expired; sign in again'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.web_push_subscriptions s
    WHERE s.user_id = v_user_id AND s.endpoint = p_endpoint AND s.revoked_at IS NULL) THEN
    RAISE EXCEPTION 'Push subscription not found';
  END IF;
  SELECT decrypted_secret INTO v_bearer FROM vault.decrypted_secrets
    WHERE name = 'atent_edge_function_service_role_key' LIMIT 1;
  IF v_bearer IS NULL OR length(v_bearer) < 20 THEN RAISE EXCEPTION 'Push service is not configured'; END IF;
  INSERT INTO public.web_push_test_requests(user_id)
  VALUES (v_user_id)
  RETURNING id INTO v_test_id;
  SELECT net.http_post(
    url := 'https://ngsexidmirortoccbatd.supabase.co/functions/v1/send-emergency-push',
    headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_bearer),
    body := jsonb_build_object('type', 'TEST', 'user_id', v_user_id, 'endpoint', p_endpoint, 'test_request_id', v_test_id),
    timeout_milliseconds := 10000
  ) INTO v_request_id;
  UPDATE public.web_push_test_requests SET request_id = v_request_id WHERE id = v_test_id;
  RETURN jsonb_build_object('request_id', v_test_id, 'status', 'queued');
END;
$$;

CREATE OR REPLACE FUNCTION public.get_web_push_test_status_session(p_session_token TEXT, p_request_id BIGINT)
RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_user_id UUID;
  v_status TEXT;
  v_http_status INTEGER;
BEGIN
  SELECT user_id INTO v_user_id FROM public.pwa_sessions
   WHERE token_hash = extensions.digest(convert_to(coalesce(p_session_token, ''), 'UTF8'), 'sha256')
     AND revoked_at IS NULL AND expires_at > now()
   LIMIT 1;
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'Web session expired; sign in again'; END IF;
  SELECT status, http_status INTO v_status, v_http_status
    FROM public.web_push_test_requests WHERE id = p_request_id AND user_id = v_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Push test request not found'; END IF;
  RETURN jsonb_build_object('status', v_status, 'http_status', v_http_status);
END;
$$;

REVOKE ALL ON FUNCTION public.send_web_push_test_session(TEXT, TEXT) FROM PUBLIC, authenticated;
REVOKE ALL ON FUNCTION public.get_web_push_test_status_session(TEXT, BIGINT) FROM PUBLIC, authenticated;
GRANT EXECUTE ON FUNCTION public.send_web_push_test_session(TEXT, TEXT) TO anon;
GRANT EXECUTE ON FUNCTION public.get_web_push_test_status_session(TEXT, BIGINT) TO anon;
